def show_help(stdscr, lang):
    """Paginate so this fits any terminal height, not just tall ones."""
    stdscr.nodelay(False)
    rows, _ = stdscr.getmaxyx()
    lines = HELP_LINES[lang]
    page_size = max(1, rows - 2)
    for start in range(0, len(lines), page_size):
        page = lines[start:start + page_size]
        stdscr.erase()
        for i, (line, attr) in enumerate(page):
            _safe_addstr(stdscr, i, 0, line, curses.color_pair(7) | attr)
        more = start + page_size < len(lines)
        footer = TEXT[lang]["help_more"] if more else TEXT[lang]["help_dismiss"]
        _safe_addstr(stdscr, min(rows - 1, len(page) + 1), 0, footer, curses.color_pair(7) | curses.A_DIM)
        stdscr.refresh()
        stdscr.getch()
    stdscr.nodelay(True)


def setup_colors():
    curses.start_color()
    curses.use_default_colors()
    curses.init_pair(1, curses.COLOR_RED, -1)
    curses.init_pair(2, curses.COLOR_BLUE, -1)
    curses.init_pair(3, curses.COLOR_YELLOW, -1)
    curses.init_pair(4, curses.COLOR_MAGENTA, -1)
    curses.init_pair(5, curses.COLOR_CYAN, -1)
    curses.init_pair(6, curses.COLOR_GREEN, -1)   # food
    curses.init_pair(7, curses.COLOR_WHITE, -1)   # hud / body


def _safe_addstr(stdscr, y, x, text, attr):
    rows, cols = stdscr.getmaxyx()
    if 0 <= y < rows and 0 <= x < cols:
        try:
            stdscr.addstr(y, x, text[: cols - x], attr)
        except curses.error:
            pass


SPARK_CHARS = " ▁▂▃▄▅▆▇█"  # blank + 8 block levels


def _sparkline(history, width=24):
    if not history:
        return SPARK_CHARS[0] * width
    values = list(history)[-width:]
    values = [SPARK_CHARS[0]] * (width - len(values)) + [
        SPARK_CHARS[1 + min(7, int(v * 8))] for v in values
    ]
    return "".join(values)


def _draw_vocab_row(stdscr, y, label, pairs, history=None):
    x = 0
    _safe_addstr(stdscr, y, x, f"{label}:", curses.color_pair(7) | curses.A_BOLD)
    x += len(label) + 2
    for token, frac in pairs:
        if token == 0:
            _safe_addstr(stdscr, y, x, "..", curses.color_pair(7) | curses.A_DIM)
        else:
            _safe_addstr(stdscr, y, x, "##", curses.color_pair(TOKEN_COLOR_PAIR[token]) | curses.A_BOLD)
        seg = f"{frac * 100:3.0f}% "
        _safe_addstr(stdscr, y, x + 2, seg, curses.color_pair(7))
        x += 2 + len(seg)
    if history is not None:
        _safe_addstr(stdscr, y, x + 2, _sparkline(history), curses.color_pair(7) | curses.A_DIM)


def choose_language(stdscr):
    stdscr.nodelay(False)
    stdscr.erase()
    lines = [
        ("Thronglets", curses.A_BOLD),
        ("", 0),
        ("Choose your language / Choisis ta langue :", curses.A_BOLD),
        ("  E = English", 0),
        ("  F = Francais (defaut)", 0),
        ("", 0),
        ("Press E or F to continue, or ENTER for the default (Francais).", curses.A_DIM),
    ]
    for i, (line, attr) in enumerate(lines):
        _safe_addstr(stdscr, i, 0, line, curses.color_pair(7) | attr)
    stdscr.refresh()

    lang = None
    while lang is None:
        key = stdscr.getch()
        if key in (ord("e"), ord("E")):
            lang = "en"
        elif key in (ord("f"), ord("F")) or key in ENTER_KEYS:
            lang = "fr"
    stdscr.nodelay(True)
    return lang


