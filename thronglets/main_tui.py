def _flash_message(stdscr, lang, text):
    stdscr.nodelay(False)
    stdscr.erase()
    _safe_addstr(stdscr, 0, 0, text, curses.color_pair(1) | curses.A_BOLD)
    _safe_addstr(stdscr, 2, 0, TEXT[lang]["flash_hint"], curses.color_pair(7) | curses.A_DIM)
