def draw(stdscr, world, paused, speed, mode, placing, cursor, lang, trained=False):
    t = TEXT[lang]
    labels = STATE_LABELS[lang]
    stdscr.erase()
    rows, cols = stdscr.getmaxyx()
    field_h = max(1, rows - HUD_H)
    field_w = max(1, cols)
    sx, sy = (field_w - 1) / WIDTH, (field_h - 1) / HEIGHT

    pop = world.population()
    status = t["hud_paused"] if paused else f"x{speed}"
    tag = t["hud_trained_tag"] if trained else ""
    header = t["hud_header"].format(tick=world.tick, pop=pop, births=world.births,
                                     deaths=world.deaths, status=status, tag=tag)
    _safe_addstr(stdscr, 0, 0, header, curses.color_pair(7) | curses.A_BOLD)

    if mode == "manual":
        placing_label = t["placing_food"] if placing == "food" else t["placing_predator"]
        settings = t["hud_manual"].format(placing=placing_label)
    else:
        settings = t["hud_auto"].format(count=len(world.predators))
    _safe_addstr(stdscr, 1, 0, settings, curses.color_pair(7) | curses.A_DIM)

    breakdown = world.vocabulary_breakdown()
    for row, state in enumerate((DANGER, FOOD, DISTRESS, MATE, IDLE), start=2):
        _draw_vocab_row(stdscr, row, labels[state], breakdown[state], world.vocab_history[state])

    _safe_addstr(stdscr, HUD_H - 3, 0, t["hud_legend"], curses.color_pair(7) | curses.A_DIM)
    food_hint = t["food_hint_auto"] if mode == "auto" else t["food_hint_manual"]
    _safe_addstr(stdscr, HUD_H - 2, 0, t["hud_controls1"].format(food_hint=food_hint),
                 curses.color_pair(7) | curses.A_DIM)
    _safe_addstr(stdscr, HUD_H - 1, 0, t["hud_controls2"], curses.color_pair(7) | curses.A_DIM)

    for fx, fy in world.food:
        y, x = HUD_H + int(fy * sy), int(fx * sx)
        _safe_addstr(stdscr, y, x, ".", curses.color_pair(6))

    for c in world.creatures:
        if not c.alive:
            continue
        y, x = HUD_H + int(c.pos[1] * sy), int(c.pos[0] * sx)
        pair = TOKEN_COLOR_PAIR.get(c.token, 7)
        _safe_addstr(stdscr, y, x, "o", curses.color_pair(pair) | curses.A_BOLD)

    for p in world.predators:
        y, x = HUD_H + int(p.pos[1] * sy), int(p.pos[0] * sx)
        _safe_addstr(stdscr, y, x, "X", curses.color_pair(1) | curses.A_BOLD)

    if mode == "manual":
        cy, cx = HUD_H + int(cursor[1] * sy), int(cursor[0] * sx)
        pair = 6 if placing == "food" else 1
        _safe_addstr(stdscr, cy, cx, "+", curses.color_pair(pair) | curses.A_BOLD | curses.A_REVERSE)

    if pop == 0:
        _safe_addstr(stdscr, HUD_H + field_h // 2, max(0, cols // 2 - 12),
                     t["extinct"], curses.color_pair(1) | curses.A_BOLD)

    stdscr.refresh()


def _new_world(mode, predator_count, init_pop=DEFAULT_INIT_POP, seed_genome=None):
    if mode == "manual":
        return World(init_pop=init_pop, manual_food=True, manual_predators=True, seed_genome=seed_genome)
    return World(init_pop=init_pop, predator_count=predator_count, seed_genome=seed_genome)


def run(stdscr, language_path=None):
    curses.curs_set(0)
    setup_colors()

    lang = choose_language(stdscr)

    world = None
    if os.path.exists(DEFAULT_SAVE_FILE) and choose_resume(stdscr, lang):
        try:
            world = load_world(DEFAULT_SAVE_FILE)
            mode = "manual" if (world.manual_food or world.manual_predators) else "auto"
            init_pop = world.population()
        except (OSError, ValueError, KeyError):
            world = None
            _flash_message(stdscr, lang, TEXT[lang]["resume_load_failed"].format(file=DEFAULT_SAVE_FILE))

    seed_genome = None
    if world is None:
        mode = choose_mode(stdscr, lang)
        init_pop = choose_population(stdscr, lang)

        if language_path:
            seed_genome = load_seed_genome(language_path)
        elif choose_ai(stdscr, lang):
            try:
                seed_genome = load_seed_genome(DEFAULT_LANGUAGE_FILE)
            except OSError:
                seed_genome = None
                _flash_message(stdscr, lang, TEXT[lang]["ai_missing_file"].format(file=DEFAULT_LANGUAGE_FILE))
        world = _new_world(mode, 6, init_pop, seed_genome)

    placing = "food"
    cursor = [WIDTH / 2, HEIGHT / 2]

    paused = False
    speed = 1  # ticks per real second
    frame_time = 1 / 20
    tick_accumulator = 0.0

    while True:
        key = stdscr.getch()
        if key in (ord("q"), 27):
            break
        elif key == ord(" "):
            paused = not paused
        elif key == ord("r"):
            world = _new_world(mode, len(world.predators), init_pop, seed_genome)
        elif key in (ord("+"), ord("=")):
            speed = min(200, speed + (1 if speed < 10 else 10))
        elif key in (ord("-"), ord("_")):
            speed = max(1, speed - (1 if speed <= 10 else 10))
        elif key == ord("f") and mode == "auto":
            world.add_food(*world.rng.uniform([10, 10], [WIDTH - 10, HEIGHT - 10]))
        elif key == ord("p"):
            placing = "predator" if placing == "food" else "food"
        elif key == ord("["):
            world.remove_predator()
        elif key == ord("]"):
            world.add_random_predator()
        elif key == ord("s"):
            save_world(world, DEFAULT_SAVE_FILE)
            _flash_message(stdscr, lang, TEXT[lang]["save_confirmed"].format(file=DEFAULT_SAVE_FILE))
        elif key == ord("h"):
            show_help(stdscr, lang)
        elif key == curses.KEY_UP:
            cursor[1] = max(0.0, cursor[1] - CURSOR_STEP)
        elif key == curses.KEY_DOWN:
            cursor[1] = min(HEIGHT, cursor[1] + CURSOR_STEP)
        elif key == curses.KEY_LEFT:
            cursor[0] = max(0.0, cursor[0] - CURSOR_STEP)
        elif key == curses.KEY_RIGHT:
            cursor[0] = min(WIDTH, cursor[0] + CURSOR_STEP)
        elif key in ENTER_KEYS and mode == "manual":
            if placing == "food":
                world.add_food(cursor[0], cursor[1])
            else:
                world.add_predator(cursor[0], cursor[1])

        if not paused:
            tick_accumulator += frame_time
            tick_interval = 1.0 / speed
            while tick_accumulator >= tick_interval:
                world.step()
                tick_accumulator -= tick_interval
        else:
            tick_accumulator = 0.0

        draw(stdscr, world, paused, speed, mode, placing, cursor, lang, trained=seed_genome is not None)
        time.sleep(frame_time)


def main():
    parser = argparse.ArgumentParser(description="Thronglets - terminal renderer")
    parser.add_argument("--language", type=str, default=None,
                         help="seed the population with a train_language.py --export vocabulary "
                              "instead of starting from scratch")
    args = parser.parse_args()

    curses.wrapper(run, args.language)


if __name__ == "__main__":
    main()
