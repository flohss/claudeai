def choose_population(stdscr, lang):
    t = TEXT[lang]
    stdscr.nodelay(False)
    stdscr.erase()
    lines = [
        ("Thronglets", curses.A_BOLD),
        ("", 0),
        (t["choose_pop_prompt"].format(max=MAX_POPULATION, default=DEFAULT_INIT_POP), curses.A_BOLD),
    ]
    for i, (line, attr) in enumerate(lines):
        _safe_addstr(stdscr, i, 0, line, curses.color_pair(7) | attr)
    _safe_addstr(stdscr, 4, 0, "> ", curses.color_pair(7))
    stdscr.refresh()

    curses.echo()
    curses.curs_set(1)
    text = stdscr.getstr(4, 2, 4).decode(errors="ignore").strip()
    curses.noecho()
    curses.curs_set(0)
    stdscr.nodelay(True)

    try:
        n = int(text)
    except ValueError:
        return DEFAULT_INIT_POP
    return max(1, min(MAX_POPULATION, n))


